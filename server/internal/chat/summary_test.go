// stubProvider 可脚本化的测试替身:
// - 摘要请求(system 含「摘要器」)→ 输出可断言的摘要文本
// - 普通对话请求 → 输出固定回答
// 用于在无真模型环境下验证摘要生成与注入逻辑。
type stubProvider struct{}

func (s *stubProvider) StreamChat(ctx context.Context, req provider.ChatRequest) (<-chan provider.StreamEvent, error) {
	events := make(chan provider.StreamEvent, 8)
	go func() {
		defer close(events)
		text := "好的回答"
		if len(req.Messages) > 0 && strings.Contains(req.Messages[0].Content, "摘要器") {
			text = "摘要:用户讨论了长对话上下文管理,决定采用摘要压缩方案。"
		}
		events <- provider.StreamEvent{Type: "delta", Content: text}
		events <- provider.StreamEvent{Type: "done", Reason: "stop"}
	}()
	return events, nil
}

func newSummaryTestOrchestrator(t *testing.T) (*Orchestrator, *model.Conversation) {
	t.Helper()
	db, err := store.Open(filepath.Join(t.TempDir(), "test.db"))
	if err != nil {
		t.Fatalf("open store: %v", err)
	}
	conv := model.Conversation{UserID: 1, Title: model.DefaultConversationTitle}
	if err := db.Create(&conv).Error; err != nil {
		t.Fatalf("create conversation: %v", err)
	}
	return &Orchestrator{DB: db, Provider: &stubProvider{}, Tools: tool.DefaultRegistry(), MaxRounds: 3}, &conv
}

func seedMessages(t *testing.T, o *Orchestrator, convID uint, rounds int) {
	t.Helper()
	for i := 0; i < rounds; i++ {
		pair := []model.Message{
			{ConversationID: convID, Role: provider.RoleUser, Content: "用户消息 " + itoa(i+1)},
			{ConversationID: convID, Role: provider.RoleAssistant, Content: "助手回答 " + itoa(i+1)},
		}
		for _, m := range pair {
			if err := o.DB.Create(&m).Error; err != nil {
				t.Fatalf("seed message: %v", err)
			}
		}
	}
}

// TestUpdateSummaryCompressesOldHistory 超过窗口条数后:窗口外历史被压缩成摘要落库,
// SummarizedCount 记录覆盖进度,buildMessages 注入摘要且原文窗口只保留最近 16 条。
func TestUpdateSummaryCompressesOldHistory(t *testing.T) {
	o, conv := newSummaryTestOrchestrator(t)
	seedMessages(t, o, conv.ID, 10) // 20 条 = 窗口 16 + 窗口外 4

	o.updateSummaryIfStale(conv.ID)

	var updated model.Conversation
	if err := o.DB.First(&updated, conv.ID).Error; err != nil {
		t.Fatalf("reload conversation: %v", err)
	}
	if !strings.Contains(updated.Summary, "摘要:用户讨论了长对话上下文管理") {
		t.Fatalf("summary should be generated by summarizer, got %q", updated.Summary)
	}
	if updated.SummarizedCount != 4 {
		t.Fatalf("SummarizedCount should be 4 (20-16), got %d", updated.SummarizedCount)
	}

	// 注入校验:buildMessages 应包含摘要 system 消息,且原文窗口只有 16 条
	msgs, err := o.buildMessages(&updated)
	if err != nil {
		t.Fatalf("buildMessages: %v", err)
	}
	if len(msgs) < 2 || msgs[0].Role != provider.RoleSystem || !strings.Contains(msgs[0].Content, "chat-forge") {
		t.Fatalf("first message should be main system prompt")
	}
	if !strings.Contains(msgs[1].Content, "【此前对话摘要】") || !strings.Contains(msgs[1].Content, updated.Summary) {
		t.Fatalf("second message should inject summary, got %q", msgs[1].Content)
	}
	raw := 0
	lastContent := ""
	for _, m := range msgs[2:] {
		if m.Role == provider.RoleSystem {
			t.Fatalf("raw window should not contain system messages")
		}
		raw++
		if m.Content != "" {
			lastContent = m.Content
		}
	}
	if raw != recentKeepMax {
		t.Fatalf("raw window should keep %d messages, got %d", recentKeepMax, raw)
	}
	if !strings.Contains(lastContent, "助手回答") {
		t.Fatalf("window should end with the newest assistant message, got %q", lastContent)
	}
}

// TestUpdateSummarySkipsShortConversation 未超窗口条数时不触发压缩。
func TestUpdateSummarySkipsShortConversation(t *testing.T) {
	o, conv := newSummaryTestOrchestrator(t)
	seedMessages(t, o, conv.ID, 5) // 10 条 < 16,窗口外为 0

	o.updateSummaryIfStale(conv.ID)

	var updated model.Conversation
	o.DB.First(&updated, conv.ID)
	if updated.Summary != "" || updated.SummarizedCount != 0 {
		t.Fatalf("short conversation should not be summarized, got %q / %d",
			updated.Summary, updated.SummarizedCount)
	}
}

// TestUpdateSummaryIncremental 新增窗口外消息后,摘要增量重压且覆盖进度前进。
func TestUpdateSummaryIncremental(t *testing.T) {
	o, conv := newSummaryTestOrchestrator(t)
	seedMessages(t, o, conv.ID, 10)
	o.updateSummaryIfStale(conv.ID)

	seedMessages(t, o, conv.ID, 3) // 再加 6 条,窗口外 4 → 10
	o.updateSummaryIfStale(conv.ID)

	var updated model.Conversation
	o.DB.First(&updated, conv.ID)
	if updated.SummarizedCount != 10 {
		t.Fatalf("SummarizedCount should advance to 10, got %d", updated.SummarizedCount)
	}
}
